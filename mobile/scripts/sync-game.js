// Copies the game from ../index.html into gameHtml.ts so the app always ships the latest version.
const fs = require('fs');
const path = require('path');

const html = fs.readFileSync(path.join(__dirname, '..', '..', 'index.html'), 'utf8');
const out = `// Generated by scripts/sync-game.js from ../index.html. Do not edit by hand.\nexport default ${JSON.stringify(html)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'gameHtml.ts'), out);
console.log('Synced game into gameHtml.ts');
